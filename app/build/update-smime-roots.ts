import { writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";

let tag = process.argv[2];
if (!/^NSS_[0-9_]+_RTM$/.test(tag ?? "")) {
  throw new Error("Usage: npm run smime:update-roots NSS_3_132_RTM");
}
// These roots decide which CAs we trust. Fetch the file from 2 independent hosts and use it
// only if both copies are identical, so that a single compromised host can't change it.
let response = await fetch(`https://hg.mozilla.org/projects/nss/raw-file/${tag}/lib/ckfw/builtins/certdata.txt`);
if (!response.ok) {
  throw new Error(`hg.mozilla.org: ${response.status} ${response.statusText}`);
}
let certdata = await response.text();
let responseAlt = await fetch(`https://raw.githubusercontent.com/mozilla/nss/${tag}/lib/ckfw/builtins/certdata.txt`);
if (!responseAlt.ok) {
  throw new Error(`GitHub: ${responseAlt.status} ${responseAlt.statusText}`);
}
let certdataAlt = await responseAlt.text();
if (certdata != certdataAlt) {
  throw new Error("certdata.txt from hg.mozilla.org and from GitHub differ");
}

let objects: Record<string, string | Buffer>[] = [];
let lines = certdata.split("\n");
for (let i = 0; i < lines.length; i++) {
  let [attribute, type, ...value] = lines[i].split(" ");
  if (attribute == "CKA_CLASS") {
    objects.push({});
  }
  if (!attribute.startsWith("CKA_")) {
    continue;
  }
  if (type == "MULTILINE_OCTAL") {
    let octal = "";
    for (i++; i < lines.length && lines[i] != "END"; i++) {
      octal += lines[i];
    }
    objects.at(-1)[attribute] = Buffer.from(octal.split("\\").slice(1).map(byte => parseInt(byte, 8)));
  } else {
    objects.at(-1)[attribute] = value.join(" ");
  }
}

let notEmailRoots: string[] = [];
let emailRoots: string[] = [];
for (let cert of objects.filter(object => object.CKA_CLASS == "CKO_CERTIFICATE")) {
  let der = cert.CKA_VALUE as Buffer;
  let sha1 = createHash("sha1").update(der).digest();
  let fingerprint = createHash("sha256").update(der).digest("hex");
  let trust = objects.find(object => object.CKA_CLASS == "CKO_NSS_TRUST" && sha1.equals(object.CKA_CERT_SHA1_HASH as Buffer));
  let label = (cert.CKA_LABEL as string).slice(1, -1);
  if (trust?.CKA_TRUST_EMAIL_PROTECTION != "CKT_NSS_TRUSTED_DELEGATOR") {
    notEmailRoots.push(`${fingerprint} ${label}\n`);
    continue;
  }
  if (cert.CKA_NSS_EMAIL_DISTRUST_AFTER instanceof Buffer) {
    throw new Error(`${label} has an email distrust date, which Mustang does not support yet`);
  }
  emailRoots.push(`# ${label}\n-----BEGIN CERTIFICATE-----\n${der.toString("base64").match(/.{1,64}/g).join("\n")}\n-----END CERTIFICATE-----\n`);
}
let sha256 = createHash("sha256").update(certdata).digest("hex");
await writeFile(new URL("../logic/Mail/Encryption/SMIME/roots/mozilla-email-roots.pem", import.meta.url),
  `# The root certificates that Mozilla trusts for email (S/MIME)
# From NSS ${tag} lib/ckfw/builtins/certdata.txt, SHA-256 ${sha256}
# License: Mozilla Public License 2.0 <https://mozilla.org/MPL/2.0/>
# Generated by app/build/update-smime-roots.ts. Do not edit.

${emailRoots.join("\n")}`);
await writeFile(new URL("../logic/Mail/Encryption/SMIME/roots/mozilla-not-email-roots.txt", import.meta.url),
  `# SHA-256 of the root certificates that Mozilla does not trust for email (S/MIME)
# From NSS ${tag} lib/ckfw/builtins/certdata.txt, SHA-256 ${sha256}
# License: Mozilla Public License 2.0 <https://mozilla.org/MPL/2.0/>
# Generated by app/build/update-smime-roots.ts. Do not edit.

${notEmailRoots.sort().join("")}`);
console.log(`${emailRoots.length} email roots, ${notEmailRoots.length} roots without email trust`);
